#!/usr/bin/env python3
"""Writes answers.json: what the grammar model says about every sentence of the
Writing check benchmark, at each KEEP bias the apps use.

    python3 answers.py MODEL_DIR           # write
    python3 answers.py MODEL_DIR --check   # fail if answers.json is stale

The benchmark (`WritingBenchmarkTest` on Android) runs the whole Writing check,
rules and model together, on the sets below. ONNX Runtime does not run in a JVM
unit test, so the model's half is read from here: each sentence exactly as
`WritingCheck` splits it (see `writing_text.py`), and the model's text for it.
Regenerate whenever a set, `infer.py`, the pinned model or a bias changes.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from infer import KEEP_BIAS, Tagger
from writing_text import sentences

HERE = Path(__file__).parent
OUT = HERE / "answers.json"

# The benchmark's sets, read by WritingBenchmarkTest too.
SETS = [
    "everyday_en.jsonl",
    "heldout_en.jsonl",
    "heldout_clean_en.jsonl",
    "typed_en.jsonl",
    "dictation_en.jsonl",
    "clean_en.jsonl",
]

# Tier name → KEEP bias. Must match GrammarTagger's constants on both platforms.
TIERS = {"balanced": KEEP_BIAS}


def build(model_dir: Path) -> str:
    asked: list[str] = []
    seen: set[str] = set()
    for name in SETS:
        for line in (HERE / name).read_text().splitlines():
            if not line.strip():
                continue
            for s in sentences(json.loads(line)["input"]):
                if s not in seen:
                    seen.add(s)
                    asked.append(s)
    doc: dict = {
        "about": "Generated by tools/grammar-eval/answers.py; do not edit. The grammar model's "
                 "text for every sentence of the Writing check benchmark sets, per tier. A "
                 "sentence the model left alone is in `sentences` but not in its tier's map.",
        "sentences": asked,
    }
    for tier, bias in TIERS.items():
        tagger = Tagger(model_dir, keep_bias=bias)
        changed = {}
        for s in asked:
            out = tagger.correct(s).output
            if out != s:
                changed[s] = out
        doc[tier] = changed
    return json.dumps(doc, ensure_ascii=False, indent=0) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("model_dir", type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build(args.model_dir)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.name} is stale; run answers.py")
        print(f"{OUT.name} is current")
        return
    OUT.write_text(text)
    doc = json.loads(text)
    print(len(doc["sentences"]), "sentences;", ", ".join(f"{t}: {len(doc[t])} changed" for t in TIERS))


if __name__ == "__main__":
    main()
